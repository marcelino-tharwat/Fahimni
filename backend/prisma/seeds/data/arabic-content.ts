export function getArabicFullName(gender: "male" | "female", index: number): string {
  const firstNames = gender === "male" ? ARABIC_FIRST_NAMES_MALE : ARABIC_FIRST_NAMES_FEMALE;
  const firstName = firstNames[index % firstNames.length]!;
  const lastName = ARABIC_LAST_NAMES[Math.floor(index / ARABIC_LAST_NAMES.length) % ARABIC_LAST_NAMES.length]!;
  const firstName2 = firstNames[(index + 37) % firstNames.length]!;
  return gender === "male" ? `${firstName} ${lastName}` : `${firstName2} ${lastName}`;
}
